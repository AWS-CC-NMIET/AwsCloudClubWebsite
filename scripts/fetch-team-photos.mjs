#!/usr/bin/env node
// scripts/fetch-team-photos.mjs
// Download team photos from Google Drive, smart-crop them to 4:5 portraits
// (sharp's attention strategy keeps the face in frame), save small WebP files
// to public/team/, and regenerate lib/team-photos.ts.
//
// The Drive files must be shared as "Anyone with the link can view". The
// memberId → Drive id map lives in scripts/team-photos.source.json (gitignored).
// Re-runnable: already-processed photos are skipped unless --force is passed.
//
// Usage: node scripts/fetch-team-photos.mjs [--force]

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "fs"
import { createRequire } from "module"

const require = createRequire(import.meta.url)
const sharp = require("sharp")

const root = new URL("..", import.meta.url)
const outDir = new URL("public/team/", root)
// memberId → Google Drive file id. Kept out of git (the repo is public).
const sourceFile = new URL("scripts/team-photos.source.json", root)
if (!existsSync(sourceFile)) {
  console.error("Missing scripts/team-photos.source.json ({ \"m-member-id\": \"<drive file id>\" }). Ask a maintainer for it.")
  process.exit(1)
}
const source = JSON.parse(readFileSync(sourceFile, "utf8"))
const force = process.argv.includes("--force")

mkdirSync(outDir, { recursive: true })

async function download(driveId) {
  for (const url of [
    `https://drive.google.com/thumbnail?id=${driveId}&sz=w1600`,
    `https://drive.google.com/uc?export=download&id=${driveId}`,
  ]) {
    const res = await fetch(url, { redirect: "follow" })
    const type = res.headers.get("content-type") ?? ""
    if (res.ok && type.startsWith("image/")) return Buffer.from(await res.arrayBuffer())
  }
  return null
}

let ok = 0
const skipped = []
for (const [memberId, driveId] of Object.entries(source)) {
  if (memberId.startsWith("_")) continue
  const file = new URL(`${memberId}.webp`, outDir)
  if (existsSync(file) && !force) {
    ok++
    continue
  }
  const image = await download(driveId)
  if (!image) {
    skipped.push(memberId)
    continue
  }
  await sharp(image)
    .rotate() // respect EXIF orientation from phone cameras
    .resize(640, 800, { fit: "cover", position: sharp.strategy.attention })
    .webp({ quality: 80 })
    .toFile(file.pathname.replace(/^\/([A-Za-z]:)/, "$1"))
  ok++
  console.log(`✓ ${memberId}`)
}

// Manifest of every photo that exists on disk.
const ids = readdirSync(outDir)
  .filter(f => f.endsWith(".webp"))
  .map(f => f.replace(/\.webp$/, ""))
  .sort()
writeFileSync(
  new URL("lib/team-photos.ts", root),
  `// lib/team-photos.ts — generated by scripts/fetch-team-photos.mjs. Do not edit by hand.\n` +
    `// Maps team member id → processed photo in /public/team.\n\n` +
    `export const TEAM_PHOTOS: Record<string, string> = {\n` +
    ids.map(id => `  "${id}": "/team/${id}.webp",`).join("\n") +
    (ids.length ? "\n" : "") +
    `}\n`
)

console.log(`\n${ok} photos ready, ${skipped.length} not downloadable.`)
if (skipped.length) {
  console.log(`Not shared publicly (Drive asked for sign-in): ${skipped.join(", ")}`)
  console.log(`Share the upload folder as "Anyone with the link can view" and run this again.`)
}
