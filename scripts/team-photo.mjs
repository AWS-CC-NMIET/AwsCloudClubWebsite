#!/usr/bin/env node
// scripts/team-photo.mjs
// Add or replace a team member's portrait: crop to 4:5, resize to 720×900,
// save public/team/<memberId>.webp and regenerate lib/team-photos.ts.
//
//   node scripts/team-photo.mjs <memberId> <image> [--focus x,y] [--enhance]
//
// <memberId>  roster id from lib/club-content.ts, e.g. m-neha
// <image>     ideally a transparent PNG cut-out (background removed) — cards
//             detect transparency and stand the person on the team livery;
//             regular photos work too and are vignetted instead
// --focus     where the face is in the source, as fractions (e.g. 0.42,0.44); the
//             crop frames it in the upper third. Without it, sharp picks the most
//             salient area. Skip it if the image is already a 4:5 chest-up crop.
// --enhance   lifts brightness/contrast slightly and sharpens (dim phone photos)
//
// Remove a portrait by deleting public/team/<memberId>.webp and running
//   node scripts/team-photo.mjs --manifest

import { existsSync, mkdirSync, readdirSync, writeFileSync } from "fs"
import { fileURLToPath } from "url"
import { createRequire } from "module"

const require = createRequire(import.meta.url)
const sharp = require("sharp")

const root = new URL("..", import.meta.url)
const outDir = new URL("public/team/", root)
const OUT_W = 720
const OUT_H = 900

/** Crop to a 4:5 portrait (around `focus` if given) and save as WebP, keeping transparency. */
async function savePortrait(input, memberId, { focus, enhance = false } = {}) {
  // Bake in EXIF rotation first so the focus point refers to the upright image.
  const upright = await sharp(input).rotate().toBuffer()
  let image = sharp(upright)
  if (focus) {
    const { width, height } = await image.metadata()
    // Largest 4:5 window, zoomed in a little only when that doesn't mean
    // upscaling, with the face at 50% / 30%.
    const max = Math.min(width, (height * 4) / 5)
    const w = Math.round(Math.max(Math.min(max, OUT_W), max * 0.9))
    const h = Math.round((w * 5) / 4)
    const clamp = (v, limit) => Math.max(0, Math.min(limit, Math.round(v)))
    image = image.extract({
      left: clamp(focus.x * width - w * 0.5, width - w),
      top: clamp(focus.y * height - h * 0.3, height - h),
      width: w,
      height: h,
    })
  }
  const sized = await image.resize(OUT_W, OUT_H, { fit: "cover", position: sharp.strategy.attention }).png().toBuffer()

  let out = sharp(sized)
  if (enhance) {
    // Adjust colour only — the alpha channel (cut-outs) is split off and re-attached.
    const { hasAlpha } = await sharp(sized).metadata()
    const rgb = await sharp(sized)
      .removeAlpha()
      .modulate({ brightness: 1.06, saturation: 1.1 })
      .linear(1.1, -10)
      .sharpen({ sigma: 0.8 })
      .png()
      .toBuffer()
    out = hasAlpha ? sharp(rgb).joinChannel(await sharp(sized).extractChannel(3).png().toBuffer()) : sharp(rgb)
  }
  await out.webp({ quality: 86, alphaQuality: 100 }).toFile(fileURLToPath(new URL(`${memberId}.webp`, outDir)))
}

/** Regenerate lib/team-photos.ts from the portraits on disk. */
function writeManifest() {
  const ids = readdirSync(outDir)
    .filter(f => f.endsWith(".webp"))
    .map(f => f.replace(/\.webp$/, ""))
    .sort()
  writeFileSync(
    new URL("lib/team-photos.ts", root),
    `// lib/team-photos.ts — generated by scripts/team-photo.mjs. Do not edit by hand.\n` +
      `// Maps team member id → portrait in /public/team.\n\n` +
      `export const TEAM_PHOTOS: Record<string, string> = {\n` +
      ids.map(id => `  "${id}": "/team/${id}.webp",`).join("\n") +
      (ids.length ? "\n" : "") +
      `}\n`
  )
  return ids.length
}

mkdirSync(outDir, { recursive: true })
const args = process.argv.slice(2)

if (args[0] === "--manifest") {
  console.log(`${writeManifest()} portraits in lib/team-photos.ts`)
  process.exit(0)
}

const [memberId, file] = args
const focusArg = args.includes("--focus") ? args[args.indexOf("--focus") + 1] ?? "" : null
const [fx, fy] = focusArg?.split(",").map(Number) ?? []
const focus = fx >= 0 && fx <= 1 && fy >= 0 && fy <= 1 ? { x: fx, y: fy } : undefined
if (!memberId?.startsWith("m-") || !file || !existsSync(file) || (focusArg !== null && !focus)) {
  console.error("Usage: node scripts/team-photo.mjs <memberId e.g. m-neha> <image> [--focus x,y] [--enhance]")
  process.exit(1)
}
await savePortrait(file, memberId, { focus, enhance: args.includes("--enhance") })
console.log(`✓ ${memberId}  (${writeManifest()} portraits in lib/team-photos.ts)`)
